CREATE DATABASE IF NOT EXISTS netwatch_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE netwatch_db;
CREATE TABLE IF NOT EXISTS users(
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,name VARCHAR(120) NOT NULL,email VARCHAR(160) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,role ENUM('admin','engineer','viewer') NOT NULL DEFAULT 'viewer',
 active BOOLEAN NOT NULL DEFAULT TRUE,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sites(
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,name VARCHAR(150) NOT NULL,code VARCHAR(40) NOT NULL UNIQUE,
 city VARCHAR(100) NOT NULL,address VARCHAR(255),latitude DECIMAL(10,7),longitude DECIMAL(10,7),
 active BOOLEAN NOT NULL DEFAULT TRUE,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS devices(
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,site_id BIGINT UNSIGNED NOT NULL,name VARCHAR(150) NOT NULL,
 type ENUM('router','switch','antenna','server','firewall','other') NOT NULL,
 manufacturer VARCHAR(100),model VARCHAR(100),ip_address VARCHAR(45),serial_number VARCHAR(100),
 status ENUM('online','offline','maintenance') NOT NULL DEFAULT 'online',active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_devices_site FOREIGN KEY(site_id) REFERENCES sites(id),UNIQUE KEY uq_serial(serial_number),
 INDEX idx_device_status(status),INDEX idx_device_site(site_id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS incidents(
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,title VARCHAR(180) NOT NULL,description TEXT,
 priority ENUM('low','medium','high','critical') NOT NULL DEFAULT 'medium',
 status ENUM('open','in_progress','resolved') NOT NULL DEFAULT 'open',
 site_id BIGINT UNSIGNED NULL,device_id BIGINT UNSIGNED NULL,assigned_to BIGINT UNSIGNED NULL,reported_by BIGINT UNSIGNED NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,resolved_at DATETIME NULL,
 CONSTRAINT fk_incident_site FOREIGN KEY(site_id) REFERENCES sites(id) ON DELETE SET NULL,
 CONSTRAINT fk_incident_device FOREIGN KEY(device_id) REFERENCES devices(id) ON DELETE SET NULL,
 CONSTRAINT fk_incident_assignee FOREIGN KEY(assigned_to) REFERENCES users(id) ON DELETE SET NULL,
 CONSTRAINT fk_incident_reporter FOREIGN KEY(reported_by) REFERENCES users(id) ON DELETE SET NULL,
 INDEX idx_incident_status_priority(status,priority),INDEX idx_incident_created(created_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS monitoring_events(
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,device_id BIGINT UNSIGNED NOT NULL,
 event_type ENUM('info','warning','recovery') NOT NULL,message VARCHAR(255) NOT NULL,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_event_device FOREIGN KEY(device_id) REFERENCES devices(id) ON DELETE CASCADE,INDEX idx_event_created(created_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS audit_logs(
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,user_id BIGINT UNSIGNED NULL,action VARCHAR(60) NOT NULL,
 entity VARCHAR(60) NOT NULL,entity_id BIGINT UNSIGNED NULL,details JSON NULL,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_audit_user FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;
